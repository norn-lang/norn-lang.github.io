/**
 * Builds index.html from src/index.html and the programs in src/programs.
 *
 *   node tools/build.ts --norn ../norn
 *
 * It needs a checkout of https://github.com/norn-lang/norn with `npm ci` run,
 * and uses it twice: `norn check` must pass on every program shown on the
 * site, and the code is coloured by the playground's highlighter, which reads
 * tokens from Norn's own lexer. The output is committed, because GitHub Pages
 * publishes this repository as it is.
 *
 * In src/index.html:
 *   <!--norn:NAME-->   the highlighted lines of src/programs/NAME.norn
 *   {{play:NAME}}      a playground link that opens that program
 */
import { execFileSync } from "node:child_process";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { deflateRawSync } from "node:zlib";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const nornFlag = process.argv.indexOf("--norn");
if (nornFlag === -1 || !process.argv[nornFlag + 1]) {
  console.error("usage: node tools/build.ts --norn <path to a norn checkout>");
  process.exit(2);
}
const norn = resolve(process.argv[nornFlag + 1]!);
const programs = join(root, "src/programs");
const playground = "https://norn-lang.org/norn/";

// A program that does not check never reaches the page.
execFileSync(process.execPath, [join(norn, "src/cli.ts"), "check", programs], { stdio: "inherit", cwd: norn });

interface Highlight { from: number; to: number; style: string }
const { highlights } = (await import(pathToFileURL(join(norn, "playground/src/highlight.ts")).href)) as {
  highlights: (source: string) => Highlight[];
};

const escape = (text: string) => text.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

/** One block element per line, so that a line can be marked; spans never cross a line. */
function render(source: string): string {
  const marks = highlights(source);
  const lines: string[] = [];
  let offset = 0;
  for (const text of source.replace(/\n$/, "").split("\n")) {
    const end = offset + text.length;
    let html = "";
    let at = offset;
    for (const mark of marks) {
      const from = Math.max(mark.from, offset);
      const to = Math.min(mark.to, end);
      if (to <= from) continue;
      html += escape(source.slice(at, from));
      html += `<span class="tok-${mark.style}">${escape(source.slice(from, to))}</span>`;
      at = to;
    }
    html += escape(source.slice(at, end));
    lines.push(`<span class="ln">${html}</span>`);
    offset = end + 1;
  }
  return lines.join("");
}

/** Examples the playground ships are linked by name; any other program travels in the fragment. */
function link(name: string, source: string): string {
  let shipped: string | null = null;
  try {
    shipped = readFileSync(join(norn, "examples", `${name}.norn`), "utf8");
  } catch {}
  if (shipped === source) return `${playground}#example=${encodeURIComponent(name)}`;
  return `${playground}#code=${deflateRawSync(Buffer.from(source, "utf8")).toString("base64url")}`;
}

const sources = new Map<string, string>();
for (const file of readdirSync(programs)) {
  if (file.endsWith(".norn")) sources.set(file.replace(/\.norn$/, ""), readFileSync(join(programs, file), "utf8"));
}
const source = (name: string) => {
  const text = sources.get(name);
  if (text === undefined) throw new Error(`src/index.html names ${name}, and src/programs/${name}.norn does not exist`);
  return text;
};

const page = readFileSync(join(root, "src/index.html"), "utf8")
  .replace(/<!--norn:([\w-]+)-->/g, (_, name: string) => render(source(name)))
  .replace(/\{\{play:([\w-]+)\}\}/g, (_, name: string) => link(name, source(name)));

writeFileSync(join(root, "index.html"), page.replace("<!doctype html>\n", "<!doctype html>\n<!-- Generated by tools/build.ts from src/index.html: edit that file. -->\n"));
console.log(`index.html: ${sources.size} programs checked`);
